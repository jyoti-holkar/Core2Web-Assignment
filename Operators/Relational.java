
    public class Relational {
    public static void main(String[] args) {
        int a=7;
        int b=5;

        System.out.println("First Number="+a);
        System.out.println("Second Number="+b);

        System.out.println(7>5);
        System.out.println(7<5);
        System.out.println(7==5);
        System.out.println(7!=5);
        System.out.println(7>=5);
        System.out.println(7<=5);
    }
    
}

    
