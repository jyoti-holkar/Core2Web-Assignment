public class Arithmetic {
    public static void main(String[] args) {
        int firstno=10;
        int secondno=5;

        System.out.println("First Number="+firstno);
        System.out.println("Second Number="+secondno);

        System.out.println("Addition="+(firstno+secondno));
        System.out.println("Subtration="+(firstno-secondno));
        System.out.println("Mulitiplication="+(firstno*secondno));
        System.out.println("Division="+(firstno/secondno));
        
    }
    
}
